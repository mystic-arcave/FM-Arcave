ACC = {
    "acute": ("...#.", "..#.."), "grave": (".#...", "..#.."), "circ": ("..#..", ".#.#."),
    "uml": (".....", ".#.#."), "tilde": (".##.#", "#.##."), "ring": ("..#..", "..#.."),
    "breve": (".#.#.", "..#.."), "dot": (".....", "..#.."),
}
COMPOSED = {
    "Ä": ("A", "uml"), "Ö": ("O", "uml"), "Ü": ("U", "uml"), "Å": ("A", "ring"),
    "É": ("E", "acute"), "È": ("E", "grave"), "Ê": ("E", "circ"), "Ë": ("E", "uml"),
    "À": ("A", "grave"), "Â": ("A", "circ"), "Á": ("A", "acute"),
    "Î": ("I", "circ"), "Ï": ("I", "uml"), "Í": ("I", "acute"),
    "Ô": ("O", "circ"), "Ó": ("O", "acute"),
    "Ù": ("U", "grave"), "Û": ("U", "circ"), "Ú": ("U", "acute"),
    "Ñ": ("N", "tilde"), "Ç": ("C", None),
    "Ğ": ("G", "breve"), "İ": ("I", "dot"), "Ş": ("S", None),   # Turkish (its I without a dot is the plain I)
}

glyphs = {}   # cp -> (w, [8 rows])
for ch, rows in G.items():
    glyphs[ord(ch)] = (len(rows[0]), ["", ""] + rows + [""])
for ch, (b, acc) in COMPOSED.items():
    rows = G[b]
    w = len(rows[0])
    top = ["", ""]
    bot = ""
    if acc:
        a = ACC[acc]
        if w < 5:   # the narrow I: centre a three-wide accent
            a = tuple({"...#.": "..#", "..#..": ".#.", ".#...": "#..", ".#.#.": "#.#", ".....": "..."}[r] for r in a)
        top = list(a)
    else:
        bot = "..#.."   # cedilla
    glyphs[ord(ch)] = (w, top + rows + [bot])
# a comma and semicolon hang below the line
for ch in ",;":
    w, rows = glyphs[ord(ch)]
    glyphs[ord(ch)] = (w, ["", "", ""] + rows[2:7])


def bits(r, w):
    v = 0
    for i, c in enumerate(r.ljust(w, ".")[:8]):
        if c == "#":
            v |= 0x80 >> i
    return v


cps = sorted(glyphs)
out = []
w_ = out.append
w_("/* SPDX-License-Identifier: GPL-3.0-only */")
w_("/* FM-ARCAVE's tables. Written by tools/gen_tables.py: do not edit. */")
w_("static const int16_t AC_SIN[257] = {   /* a quarter wave, Q14 */")
q = [round(math.sin(i / 256 * math.pi / 2) * 16384) for i in range(257)]
for k in range(0, 257, 16):
    w_("    " + ",".join(map(str, q[k:k + 16])) + ",")
w_("};")
w_("static const uint32_t AC_INC[12] = {   /* MIDI 120..131: f * 2^32 / 44100; lower octaves shift right */")
w_("    " + ",".join(f"{round(440 * 2 ** ((n - 69) / 12) * 2 ** 32 / 44100)}u" for n in range(120, 132)) + ",")
w_("};")
w_("static const uint16_t AC_SKYF[240] = {   /* Slow Glass's sky: how far down its eight colours each row is, Q8 */")
sk = [min(7 * 256 - 1, round((y / 200) ** 1.25 * 7 * 256)) for y in range(240)]
for k in range(0, 240, 16):
    w_("    " + ",".join(map(str, sk[k:k + 16])) + ",")
w_("};")
w_(f"#define FNT_N {len(cps)}")
w_("static const uint16_t FNT_CP[FNT_N] = {" + ",".join(str(c) for c in cps) + "};")
w_("static const uint8_t FNT_W[FNT_N] = {" + ",".join(str(glyphs[c][0]) for c in cps) + "};")
w_("static const uint8_t FNT_ROW[FNT_N][8] = {   /* rows 0-1 accents, 2-6 the letter, 7 below the line; bit 7 = left */")
for c in cps:
    wd, rows = glyphs[c]
    w_("    {" + ",".join(f"0x{bits(r, wd):02X}" for r in rows) + "},")
w_("};")
dst = Path(__file__).resolve().parent.parent / "firmware" / "gen" / "arcave_tab.h"
dst.write_text("\n".join(out) + "\n")
print(f"{dst}: {len(cps)} glyphs")
